# Define assets
cash = 500
savings = 2000
car_value = 5000

# Define debts
credit_card_debt = 700
car_loan = 1800

# Calculate totals
total_assets = cash + savings + car_value
total_debts = credit_card_debt + car_loan

# Calculate net worth
net_worth = total_assets - total_debts

# Display results
print(f"Your total assets are {total_assets}")
print(f"Your total debts are {total_debts}")
print(f"Your net worth is {net_worth}")